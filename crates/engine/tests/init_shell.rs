#[test]
fn soft_and_purge_shell_uninstall_preserves_user_profile() {
    use forgum_platform::shell::{remove_all_forgum_blocks, remove_delimited_block};

    let user_bashrc = r#"
# User Custom Aliases
export PATH="$HOME/bin:$PATH"
alias ll="ls -la"
alias gs="git status"

# >>> forgum (bash) >>>
# Generated by forgum init bash — do not edit by hand
__FORGUM_ENGINE="/usr/local/bin/forgum"
forgum() {
  "$__FORGUM_ENGINE" "$@"
}
# <<< forgum <<<

# >>> forgum completions (bash) >>>
# Generated by forgum completions bash
complete -F _forgum forgum
# <<< forgum completions <<<

# Prompt configuration
export PS1="\u@\h:\w\$ "
"#;

    // 1. Single delimited block removal (e.g. removing completions only)
    let (after_hook_removal, removed_hook) =
        remove_delimited_block(user_bashrc, "# >>> forgum (bash) >>>", "# <<< forgum <<<");
    assert!(removed_hook, "Target hook block must be removed");
    assert!(!after_hook_removal.contains("__FORGUM_ENGINE"));
    assert!(after_hook_removal.contains("alias ll=\"ls -la\""));
    assert!(after_hook_removal.contains("# >>> forgum completions (bash) >>>"));

    // 2. Full uninstallation: remove all forgum blocks cleanly
    let (cleaned, removed_all) = remove_all_forgum_blocks(user_bashrc.to_string());
    assert!(removed_all, "All forgum blocks must be removed");
    assert!(!cleaned.contains(">>> forgum"));
    assert!(!cleaned.contains("<<< forgum"));
    assert!(!cleaned.contains("__FORGUM_ENGINE"));
    assert!(!cleaned.contains("complete -F _forgum"));

    // User's original configuration must remain 100% intact
    assert!(cleaned.contains("export PATH=\"$HOME/bin:$PATH\""));
    assert!(cleaned.contains("alias ll=\"ls -la\""));
    assert!(cleaned.contains("alias gs=\"git status\""));
    assert!(cleaned.contains("export PS1=\"\\u@\\h:\\w\\$ \""));
}

#[test]
fn shell_sweepers_reset_scroll_margins_and_guard_split_launch() {
    // Bash
    let bash = generate_hook(Shell::Bash, ENGINE);
    assert!(
        bash.contains("printf '\\x1b[r'"),
        "bash sweeper must reset scroll margins with \\x1b[r"
    );
    assert!(
        bash.contains("if [ ! -f \"$state\" ]; then"),
        "bash split mode must guard against duplicate daemon launch"
    );

    // Zsh
    let zsh = generate_hook(Shell::Zsh, ENGINE);
    assert!(
        zsh.contains("printf '\\x1b[r'"),
        "zsh sweeper must reset scroll margins with \\x1b[r"
    );
    assert!(
        zsh.contains("if [ ! -f \"$state\" ]; then"),
        "zsh split mode must guard against duplicate daemon launch"
    );

    // Fish
    let fish = generate_hook(Shell::Fish, ENGINE);
    assert!(
        fish.contains("printf '\\x1b[r'"),
        "fish sweeper must reset scroll margins with \\x1b[r"
    );
    assert!(
        fish.contains("if not test -f $state"),
        "fish split mode must guard against duplicate daemon launch"
    );

    // PowerShell / Pwsh
    let pwsh = generate_hook(Shell::Pwsh, ENGINE);
    assert!(
        pwsh.contains("[Console]::Write(\"$esc[r\")"),
        "pwsh sweeper must reset scroll margins with $esc[r"
    );
    assert!(
        pwsh.contains("if (-not (Test-Path $state))"),
        "pwsh split mode must guard against duplicate daemon launch"
    );

    let ps = generate_hook(Shell::PowerShell, ENGINE);
    assert!(
        ps.contains("[Console]::Write(\"$esc[r\")"),
        "powershell sweeper must reset scroll margins with $esc[r"
    );
    assert!(
        ps.contains("if (-not (Test-Path $state))"),
        "powershell split mode must guard against duplicate daemon launch"
    );
}
