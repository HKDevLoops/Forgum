#[test]
fn every_shell_hook_has_consistent_delimiters() {
    for &shell in Shell::ALL {
        let hook = generate_hook(shell, ENGINE);
        if shell == Shell::Cmd {
            assert!(
                hook.contains("rem >>> forgum (cmd) >>>"),
                "cmd hook must contain 'rem >>> forgum (cmd) >>>'"
            );
            assert!(
                hook.contains("rem <<< forgum <<<"),
                "cmd hook must contain 'rem <<< forgum <<<'"
            );
        } else {
            let expected_header = format!("# >>> forgum ({shell}) >>>");
            assert!(
                hook.contains(&expected_header),
                "shell {shell} hook must contain '{expected_header}'"
            );
            assert!(
                hook.contains("# <<< forgum <<<"),
                "shell {shell} hook must contain '# <<< forgum <<<'"
            );
        }
    }
}

#[test]
fn every_shell_hook_has_standard_forgum_header_comment() {
    for &shell in Shell::ALL {
        let hook = generate_hook(shell, ENGINE);
        let expected = format!("Generated by forgum init {shell} — do not edit by hand");
        let header_line = hook
            .lines()
            .find(|l| l.contains("Generated by"))
            .unwrap_or_else(|| {
                panic!("shell {shell} missing 'Generated by' comment line in:\n{hook}")
            });
        assert!(
            header_line.contains(&expected),
            "shell {shell} header comment mismatch. Expected substring: '{expected}'. Got line: '{header_line}'"
        );
        assert!(
            !header_line.contains("forgum-engine"),
            "shell {shell} header comment must say 'forgum', not 'forgum-engine': '{header_line}'"
        );
    }
}

#[test]
fn every_shell_hook_is_cleanly_uninstalled_by_marker_delimiters() {
    for &shell in Shell::ALL {
        let hook = generate_hook(shell, ENGINE);
        // 1. Standalone removal
        let (cleaned_alone, removed_alone) =
            forgum_platform::remove_all_forgum_blocks(hook.clone());
        assert!(
            removed_alone,
            "shell {shell} standalone hook must be recognized by remove_all_forgum_blocks"
        );
        let remaining = cleaned_alone.trim();
        assert!(
            remaining.is_empty(),
            "shell {shell} standalone hook must be cleanly removed; leftover: {remaining}"
        );

        // 2. Embedded removal in user profile
        let user_rc =
            format!("# User RC Start\nexport FORGUM_TEST=1\n{hook}\nalias l='ls'\n# User RC End\n");
        let (cleaned_embedded, removed_embedded) =
            forgum_platform::remove_all_forgum_blocks(user_rc);
        assert!(
            removed_embedded,
            "embedded shell {shell} hook must be recognized and removed"
        );
        assert_eq!(
            cleaned_embedded,
            "# User RC Start\nexport FORGUM_TEST=1\nalias l='ls'\n# User RC End\n",
            "embedded shell {shell} hook must not alter surrounding user config"
        );
    }
}

