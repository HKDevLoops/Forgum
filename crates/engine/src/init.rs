fn generate_bash_hook(engine: &str, extra: &str) -> String {
    format!(
        r#"# >>> forgum (bash) >>>
# Generated by forgum-engine init bash — do not edit by hand
__FORGUM_ENGINE="{engine}"
__FORGUM_CONFIG="${{FORGUM_CONFIG:-$HOME/.config/Forgum/config.json}}"
__FORGUM_RUNTIME="${{XDG_RUNTIME_DIR:-/tmp/forgum-$UID}}/forgum"
mkdir -p "$__FORGUM_RUNTIME" 2>/dev/null

forgum() {{
  case "$1" in
    init|fortune|status|config|control|remote|profile|render|clean|preset|doctor|tmux|zellij|wezterm|screen|help)
      "$__FORGUM_ENGINE" "$@"
      return
      ;;
  esac
  local text="$*"
  if [ -z "$text" ]; then
    text="$("$__FORGUM_ENGINE" fortune 2>/dev/null)"
  fi
  "$__FORGUM_ENGINE" render \
    --config "$__FORGUM_CONFIG" \
    --text "$text" \
    --background --duration 0{extra} "$@"
}}

forgum-init() {{
  "$__FORGUM_ENGINE" init "$@"
}}

__forgum_precmd() {{
  [ -z "$__FORGUM_ENGINE" ] && return
  local state="$__FORGUM_RUNTIME/daemon.json"
  if [ -f "$state" ]; then
    local pid; pid=$(awk -F'"' '/pid/{{print $4}}' "$state" 2>/dev/null)
    if [ -n "$pid" ] && ! kill -0 "$pid" 2>/dev/null; then
      local rows; rows=$(awk -F'"' '/ob_y1/{{print $4}}' "$state" 2>/dev/null || echo 0)
      local cols=${{COLUMNS:-80}}
      printf '\x1b7'
      local y=1; while [ "$y" -le "$rows" ]; do printf '\x1b[%d;1H%*s' "$y" "$cols" ''; y=$((y+1)); done
      printf '\x1b8\x1b[0m'
      rm -f "$state"
    fi
  fi

  if [ -f "$__FORGUM_CONFIG" ]; then
    local auto; auto=$(grep -o '"auto_render_on_prompt":\s*[^,}}]*' "$__FORGUM_CONFIG" 2>/dev/null | awk '{{print $2}}')
    local mode; mode=$(grep -o '"shell_attach_mode":\s*"[^"]*"' "$__FORGUM_CONFIG" 2>/dev/null | cut -d'"' -f4)
    if [ "$auto" != "false" ]; then
      case "$mode" in
        banner) "$__FORGUM_ENGINE" render --banner --duration 1{extra} 2>/dev/null ;;
        split) printf '\x1b[9;%dr' "${{LINES:-30}}"; "$__FORGUM_ENGINE" render --background --duration 0{extra} >/dev/null 2>&1 ;;
        reactive) "$__FORGUM_ENGINE" render --background --duration 0{extra} >/dev/null 2>&1 ;;
        *) ;;
      esac
    fi
  fi
}}
if [[ -v PROMPT_COMMAND ]]; then
  PROMPT_COMMAND="__forgum_precmd${{PROMPT_COMMAND:+;$PROMPT_COMMAND}}"
else
  PROMPT_COMMAND="__forgum_precmd"
fi
# <<< forgum <<<
"#
    )
}

