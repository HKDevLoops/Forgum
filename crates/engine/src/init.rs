//! Shell hook generation for `forgum init <shell>`.
//!
//! Generates shell-specific hooks that:
//! 1. Resolve the engine path (baked at init time)
//! 2. Call `forgum-engine render` with argv flags (no JSON in shell)
//! 3. Sweep dead daemons on precmd
//!
//! Supported shells: bash, zsh, fish, pwsh (7+), powershell.exe (5.1), cmd.exe.

/// Supported shell types. Canonical definition lives in `forgum-platform::shell`;
/// re-exported here so engine code keeps using `forgum_engine::init::Shell`.
pub use forgum_platform::shell::Shell;

/// Generate a shell hook script.
///
/// `engine_path` is the absolute path to `forgum-engine`, baked in at init time.
pub fn generate_hook(shell: Shell, engine_path: &str) -> String {
    generate_hook_with_args(shell, engine_path, &[])
}

/// Generate a shell hook script with optional render arguments forwarded.
pub fn generate_hook_with_args(shell: Shell, engine_path: &str, render_args: &[String]) -> String {
    let extra = if render_args.is_empty() {
        String::new()
    } else {
        format!(" {}", render_args.join(" "))
    };
    match shell {
        Shell::Bash => generate_bash_hook(engine_path, &extra),
        Shell::Zsh => generate_zsh_hook(engine_path, &extra),
        Shell::Fish => generate_fish_hook(engine_path, &extra),
        Shell::Pwsh => generate_pwsh_hook(engine_path, &extra),
        Shell::Cmd => generate_cmd_hook(engine_path),
        Shell::PowerShell => generate_powershell_hook(engine_path, &extra),
        Shell::Elvish => generate_elvish_hook(engine_path, &extra),
        Shell::Nushell => generate_nushell_hook(engine_path, &extra),
        Shell::Xonsh => generate_xonsh_hook(engine_path, &extra),
        Shell::Tcsh => generate_tcsh_hook(engine_path, &extra),
        Shell::Ksh => generate_ksh_hook(engine_path, &extra),
        Shell::Ion => generate_ion_hook(engine_path, &extra),
        Shell::Oil => generate_oil_hook(engine_path, &extra),
        Shell::Yash => generate_yash_hook(engine_path, &extra),
        Shell::Carapace => {
            "# Carapace completion spec: run `forgum completions carapace` to install\n".to_string()
        }
    }
}

